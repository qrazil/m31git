#!/usr/bin/env python3
"""tests/conformance/commands.tsv is the one list of git's commands and what 1git
does with each. This turns it into
  * core/GIT_gitrefuse.m31: the message for a git command 1git does not run
    (dropped, out of scope, or not yet), and
  * the matrix between the markers of docs/GIT-PARITY.md,
and prints the counts.   python3 tests/conformance/gen.py [--check]
"""
import os, sys, re
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.abspath(os.path.join(here, "..", ".."))
rows = []
for line in open(os.path.join(here, "commands.tsv"), encoding="utf-8"):
    line = line.rstrip("\n")
    if not line or line.startswith("#"):
        continue
    f = line.split("\t")
    rows.append(dict(zip(["name", "group", "git", "state", "decision", "prio", "note"], f)))

USE = {
    "whatchanged": "use 1git -log --raw --no-merges",
    "pack-redundant": "use gc to repack (1git -gc, planned)",
    "filter-branch": "use git filter-repo (a separate tool that reads and writes the same repositories)",
    "help": "every command documents itself: 1git -<command> --help, 1git --help, docs/CLI-REFERENCE.md",
}
REASON = {
    "whatchanged": "it is deprecated and removed in 1git; git 3.0 removes it too (BreakingChanges: 'outlived its usefulness')",
    "pack-redundant": "it is deprecated and removed in 1git; git 3.0 removes it too (BreakingChanges: 'unusably slow')",
    "filter-branch": "it is discouraged by git itself and not in 1git ('its use is not recommended')",
    "help": "it is not in 1git",
}

def message(r):
    n = r["name"]
    if r["decision"] == "DROP":
        return "%s: %s; %s" % (n, REASON[n], USE[n])
    if r["decision"] == "OUT":
        return "%s is not in 1git: %s (docs/GIT-PARITY.md)" % (n, r["note"])
    return "%s is not in 1git yet: planned, priority %s (docs/GIT-PARITY.md)" % (n, r["prio"])

refused = [r for r in rows if r["state"] == "missing"]
out = ['// GENERATED by tests/conformance/gen.py from tests/conformance/commands.tsv: do not edit.',
       '// What 1git says for a git command it does not run: dropped on purpose, out of',
       '// scope, or planned. `refusal` answers "" for a word it knows nothing about.',
       '', 'pub str refusal(str word) {']
for r in refused:
    out.append('    if (word == "%s") {' % r["name"])
    out.append('        return "%s";' % message(r).replace("\\", "\\\\").replace('"', '\\"'))
    out.append('    }')
out += ['    return "";', '}', '']
open(os.path.join(root, "core", "GIT_gitrefuse.m31"), "w", encoding="utf-8").write("\n".join(out))

def cnt(key, val):
    return sum(1 for r in rows if r[key] == val)

lines = []
lines.append("| command | group | git 2.49 | 1git | decision | note |")
lines.append("|---|---|---|---|---|---|")
for r in rows:
    d = r["decision"] + ("" if r["prio"] == "-" else " " + r["prio"])
    lines.append("| `%s` | %s | %s | %s | %s | %s |" % (r["name"], r["group"], r["git"], r["state"], d, r["note"].replace("|", "/")))
table = "\n".join(lines)
summary = ("%d git commands in the matrix: 1git state done %d, partial %d, missing %d; decision IMPLEMENT %d, LATER %d, DROP %d, OUT of scope %d."
           % (len(rows), cnt("state", "done"), cnt("state", "partial"), cnt("state", "missing"), cnt("decision", "IMPLEMENT"), cnt("decision", "LATER"), cnt("decision", "DROP"), cnt("decision", "OUT")))
p = os.path.join(root, "docs", "GIT-PARITY.md")
doc = open(p, encoding="utf-8").read()
new = re.sub(r"(<!-- matrix:begin -->\n).*?(<!-- matrix:end -->)", lambda m: m.group(1) + summary + "\n\n" + table + "\n" + m.group(2), doc, flags=re.S)
if "--check" in sys.argv:
    sys.exit(0 if new == doc else 1)
open(p, "w", encoding="utf-8").write(new)
print(summary)
